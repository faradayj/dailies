"""Regenerate pokedoku/pokemon_data.js: one row per Pokemon form with the traits PokeDoku categories ask about.

Source, downloaded on each run: the PokeAPI CSV dump (https://github.com/PokeAPI/pokeapi).

Run: python pokedoku/build_pokemon.py
"""
import csv
import io
import json
import os
import urllib.request

CSV_URL = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/"
HERE = os.path.dirname(os.path.abspath(__file__))

REGIONS = ["kanto", "johto", "hoenn", "sinnoh", "unova", "kalos", "alola", "galar", "paldea"]  # generation 1 to 9
REGIONAL_FORMS = ["alola", "galar", "hisui", "paldea"]  # a form named "<species>-<region>..." belongs to that region
# Introduced in Legends Arceus. PokeAPI files them under generation 8 (Galar), PokeDoku under Hisui.
HISUI = {"wyrdeer", "kleavor", "ursaluna", "basculegion", "sneasler", "overqwil", "enamorus", "basculin-white-striped"}
# First-partner Pokemon. PokeAPI has no starter flag; their whole evolution lines count as starters.
STARTERS = set("""bulbasaur charmander squirtle chikorita cyndaquil totodile treecko torchic mudkip
    turtwig chimchar piplup snivy tepig oshawott chespin fennekin froakie rowlet litten popplio
    grookey scorbunny sobble sprigatito fuecoco quaxly""".split())
# First partners in Yellow and Let's Go. Only these two species count, not Pichu, Raichu or Eevee's evolutions:
# the partner cannot evolve.
PARTNERS = {"pikachu", "eevee"}


def table(name):
    """Rows of one PokeAPI CSV file as dicts keyed by column name."""
    req = urllib.request.Request(CSV_URL + name + ".csv", headers={"User-Agent": "Mozilla/5.0"})
    return list(csv.DictReader(io.StringIO(urllib.request.urlopen(req).read().decode())))


species = {s["id"]: s for s in table("pokemon_species")}
type_names = {t["id"]: t["identifier"] for t in table("types")}
types = {}  # pokemon id -> {slot: type name}
for t in table("pokemon_types"):
    types.setdefault(t["pokemon_id"], {})[t["slot"]] = type_names[t["type_id"]]
megas = {f["pokemon_id"] for f in table("pokemon_forms") if f["is_mega"] == "1"}
starter_chains = {s["evolution_chain_id"] for s in species.values() if s["identifier"] in STARTERS}
assert len(starter_chains) == len(STARTERS) == 27, "a starter name does not match PokeAPI"


def region_of(name, sp):
    for region in REGIONAL_FORMS:
        if f"-{region}" in name:
            return region
    if name in HISUI or sp["identifier"] in HISUI:
        return "hisui"
    return REGIONS[int(sp["generation_id"]) - 1]


# shortcut: every other PokeAPI form is kept (Gigantamax, Rotom appliances...), filter here if PokeDoku rejects some
pokemon = []
for p in table("pokemon"):
    # Totem, cap-Pikachu and Let's Go partner forms copy another row's traits, and their names hide the region
    # ("marowak-totem" is Alolan, "pikachu-alola-cap" is not).
    if "-totem" in p["identifier"] or p["identifier"].endswith(("-cap", "-starter")):
        continue
    sp = species[p["species_id"]]
    pokemon.append({
        "name": p["identifier"],
        "species": sp["identifier"],
        "dex": int(sp["id"]),
        "type1": types[p["id"]]["1"],
        "type2": types[p["id"]].get("2"),
        "region": region_of(p["identifier"], sp),
        "is_mega": p["id"] in megas,
        "is_legendary": sp["is_legendary"] == "1",
        "is_mythical": sp["is_mythical"] == "1",
        "is_starter": sp["evolution_chain_id"] in starter_chains or sp["identifier"] in PARTNERS,
        "is_baby": sp["is_baby"] == "1",
    })

# Self-check
by_name = {p["name"]: p for p in pokemon}
flags = lambda name: {k[3:] for k, v in by_name[name].items() if k.startswith("is_") and v}
shape = lambda name: (by_name[name]["type1"], by_name[name]["type2"], by_name[name]["region"])
assert shape("charizard-mega-x") == ("fire", "dragon", "kanto") and flags("charizard-mega-x") == {"mega", "starter"}
assert shape("vulpix-alola") == ("ice", None, "alola")
assert shape("zorua-hisui") == ("normal", "ghost", "hisui")
assert by_name["kleavor"]["region"] == "hisui"
assert flags("mewtwo") == {"legendary"} and flags("mew") == {"mythical"} and flags("pichu") == {"baby"}
assert shape("garchomp") == ("dragon", "ground", "sinnoh") and flags("garchomp") == set()
assert flags("pikachu") == flags("eevee") == {"starter"} and flags("raichu") == flags("vaporeon") == set()
assert "marowak-totem" not in by_name and "pikachu-alola-cap" not in by_name and "marowak-alola" in by_name
assert len(pokemon) > 1000 and len(by_name) == len(pokemon)
assert all(p["type1"] and p["region"] in REGIONS + ["hisui"] for p in pokemon)

with open(os.path.join(HERE, "pokemon_data.js"), "w") as f:
    rows = ",\n".join(json.dumps(p, separators=(",", ":")) for p in pokemon)
    f.write(f"// Generated by build_pokemon.py. One row per Pokemon form.\nconst POKEMON = [\n{rows}\n];\n")
print(f"pokedoku: {len(pokemon)} forms of {len({p['species'] for p in pokemon})} species, {len(megas)} megas")
